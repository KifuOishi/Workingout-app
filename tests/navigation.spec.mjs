import { test, expect } from '@playwright/test'

test('start empty, add existing and custom exercises, navigate with a running timer, finish', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-15T12:00:00') })
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/')
  await expect(page.locator('.stats')).toBeVisible()
  await expect(page.locator('#record-form')).toHaveCount(0)
  await expect(page.locator('.template-grid')).toHaveCount(0)
  await page.getByRole('button', { name: 'Start empty workout', exact: true }).click()
  await expect(page).toHaveURL(/#\/workout$/)
  const active = page.locator('#current-workout')
  await expect(active.getByRole('checkbox')).toHaveCount(0)
  await expect(active.getByRole('button', { name: 'Finish & save to history' })).toBeDisabled()
  await page.reload()
  await expect(active).toBeVisible()
  await expect(page.getByText('Could not load templates or workout progress.')).toHaveCount(0)
  await active.locator('.session-exercise-actions').getByRole('button').click()
  const add = page.locator('.session-add-form')
  await add.getByRole('button', { name: 'Shoulders', exact: true }).click()
  await add.getByRole('combobox').selectOption({ label: 'Lateral raise' })
  await add.getByRole('button', { name: 'Add to workout', exact: true }).click()
  await expect(active.getByRole('checkbox')).toHaveCount(1)
  await active.getByRole('spinbutton', { name: 'Weight 1 (kg)', exact: true }).fill('8')
  await active.getByRole('checkbox').check()
  await page.clock.runFor(30_000)
  await page.getByRole('link', { name: 'Home', exact: true }).click()
  await expect(active).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Continue workout', exact: true })).toBeVisible()
  await page.clock.runFor(30_000)
  await page.getByRole('button', { name: 'Continue workout', exact: true }).click()
  await expect(active.locator('output')).toHaveText('01:00')
  await expect(active.getByRole('checkbox')).toBeChecked()
  await active.locator('.session-exercise-actions').getByRole('button').click()
  await add.getByRole('button', { name: 'Add an exercise to', exact: false }).click()
  await add.getByPlaceholder('e.g. My custom exercise').fill('Cable Y raise')
  await add.getByRole('button', { name: 'Save and select exercise' }).click()
  await add.getByRole('button', { name: 'Add to workout', exact: true }).click()
  await expect(active.getByRole('checkbox')).toHaveCount(2)
  await expect(active.getByRole('button', { name: 'Finish & save to history' })).toBeEnabled()
  await page.getByRole('link', { name: 'Templates', exact: true }).click()
  await expect(page.locator('.template-grid')).toBeVisible()
  await expect(active).toHaveCount(0)
  await page.goBack()
  await expect(active).toBeVisible()
  await expect(active.getByRole('heading', { name: 'Cable Y raise' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await active.getByRole('checkbox').nth(1).check()
  await active.getByRole('button', { name: 'Finish & save to history' }).click()
  await expect(page).toHaveURL(/#\/history$/)
  await expect(page.locator('.history .record')).toHaveCount(2)
  await expect(page.locator('#record-form')).toHaveCount(0)
  await page.reload()
  await expect(page.locator('.history .record')).toHaveCount(2)
})
