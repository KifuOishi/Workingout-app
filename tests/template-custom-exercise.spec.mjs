import { test, expect } from '@playwright/test'

test('template editor registers and selects a custom exercise without starting a workout', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/#/templates')
  await page.getByRole('button', { name: 'Create template', exact: true }).click()
  const editor = page.locator('.template-editor')
  await editor.getByLabel('Template name').fill('Custom routine')
  await editor.getByRole('button', { name: 'Add exercise' }).click()
  const item = editor.locator('.template-item').first()
  await item.getByRole('spinbutton', { name: 'sets', exact: true }).fill('4')
  await item.getByRole('button', { name: 'Add an exercise to', exact: false }).click()
  const custom = item.locator('.custom-exercise')
  await custom.getByRole('button', { name: 'Save and select exercise', exact: true }).click()
  await expect(custom.getByRole('alert')).toBeVisible()
  await custom.getByPlaceholder('e.g. My custom exercise').fill('My shoulder press')
  await custom.getByRole('button', { name: 'Shoulders', exact: true }).click()
  await custom.getByLabel('Equipment / type', { exact: true }).selectOption('dumbbell')
  await custom.getByPlaceholder('e.g. My custom exercise').press('Enter')
  await expect(custom).toHaveCount(0)
  await expect(item.locator('.template-item-top select')).toContainText('My shoulder press')
  await expect(item.locator('.template-item-top select option:checked')).toHaveText('My shoulder press')
  await expect(item.getByRole('spinbutton', { name: 'sets', exact: true })).toHaveValue('4')
  await expect(editor).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await editor.getByRole('button', { name: 'Save template', exact: true }).click()
  await page.reload()
  await page.locator('.template-card').getByRole('button', { name: 'Edit', exact: true }).click()
  await expect(item.locator('.template-item-top select option:checked')).toHaveText('My shoulder press')
  await expect(item.getByRole('spinbutton', { name: 'sets', exact: true })).toHaveValue('4')
  await editor.getByRole('button', { name: 'Save template', exact: true }).click()
  await page.getByRole('button', { name: 'Start workout', exact: true }).click()
  await expect(page.locator('#current-workout h3').first()).toHaveText('My shoulder press')
  await expect(page.locator('#current-workout').getByRole('checkbox')).toHaveCount(4)
  const customExercises = await page.evaluate(() => JSON.parse(localStorage.getItem('workingout.exercises.v1')))
  expect(customExercises).toHaveLength(1)
  expect(customExercises[0]).toMatchObject({ name: 'My shoulder press', equipment: 'dumbbell' })
})
