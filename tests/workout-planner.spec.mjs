import { selectPreference } from './helpers/preferences.mjs'
import { test, expect } from '@playwright/test'

async function fillSets(active) {
  for (const input of await active.getByRole('spinbutton', { name: /^Weight / }).all()) await input.fill('20')
  for (const input of await active.getByRole('spinbutton', { name: /^reps / }).all()) await input.fill('10')
}

test('running timer survives reload and finishing can retry without duplicate history', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-15T12:00:00') })
  await page.goto('/#/templates')
  await page.getByRole('button', { name: 'Create template', exact: true }).click()
  await page.getByLabel('Template name').fill('Retry safe')
  const editor = page.locator('.template-editor')
  await editor.getByRole('button', { name: 'Add exercise' }).click()
  await editor.getByRole('button', { name: 'Save template' }).click()
  await page.getByRole('button', { name: 'Start workout', exact: true }).click()
  const active = page.locator('#current-workout')
  await active.getByRole('button', { name: 'Start rest', exact: true }).click()
  await page.clock.runFor(30_000)
  await page.reload()
  // Reloading also consumes wall time; allow a few seconds on busy test hosts.
  await expect(active.locator('output')).toHaveText(/^01:(?:2[5-9]|30)$/)
  await page.clock.fastForward(90_500)
  await expect(active.getByRole('alert')).toContainText('Rest is over')
  await fillSets(active)
  for (const checkbox of await active.getByRole('checkbox').all()) await checkbox.check()
  await page.evaluate(() => {
    const original = Storage.prototype.setItem
    Storage.prototype.setItem = function (key, value) {
      if (key === 'workingout.planner.v1') { Storage.prototype.setItem = original; throw new Error('Simulated storage failure') }
      return original.call(this, key, value)
    }
  })
  await active.getByRole('button', { name: 'Finish & save to history' }).click()
  await expect(page.locator('.planner > .error')).toContainText('Could not save')
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('workingout.records.v1')).length)).toBe(1)
  await active.getByRole('button', { name: 'Finish & save to history' }).click()
  await expect(active).toHaveCount(0)
  await expect(page.locator('.history .record')).toHaveCount(1)
})

test('template, timed rest, pause, reload, finish and perform again', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-15T12:00:00') })
  await page.goto('/#/templates')
  await page.getByRole('button', { name: 'Create template', exact: true }).click()
  await page.getByLabel('Template name').fill('Upper body')
  const editor = page.locator('.template-editor')
  for (let i = 0; i < 3; i++) await editor.getByRole('button', { name: 'Add exercise' }).click()
  const items = editor.locator('.template-item')
  await items.nth(1).getByRole('combobox').selectOption({ label: 'Shoulder press' })
  await items.nth(2).getByRole('combobox').selectOption({ label: 'Lat pulldown' })
  await editor.getByRole('button', { name: 'Save template' }).click()
  await expect(page.locator('.template-card')).toHaveCount(1)
  await page.reload()
  await expect(page.locator('.template-card')).toContainText('Upper body')
  await page.getByRole('button', { name: 'Start workout', exact: true }).click()
  const active = page.locator('#current-workout')
  await expect(active.getByRole('checkbox')).toHaveCount(9)
  await fillSets(active)
  await expect(active.getByRole('button', { name: 'Finish & save to history' })).toBeEnabled()
  await active.getByRole('checkbox').nth(0).check()
  await expect(active.locator('output')).toHaveText('02:00')
  await page.clock.runFor(30_000)
  await expect(active.locator('output')).toHaveText('01:30')
  await active.getByRole('button', { name: 'Pause', exact: true }).click()
  await page.clock.runFor(10_000)
  await expect(active.locator('output')).toHaveText('01:30')
  await page.reload()
  await expect(active.getByRole('checkbox').nth(0)).toBeChecked()
  await expect(active.locator('output')).toHaveText('01:30')
  await active.getByRole('button', { name: 'Resume', exact: true }).click()
  await page.clock.runFor(90_500)
  await expect(active.getByRole('alert')).toContainText('Rest is over')
  for (const checkbox of await active.getByRole('checkbox').all()) await checkbox.check()
  await active.getByRole('button', { name: 'Finish & save to history' }).click()
  await expect(active).toHaveCount(0)
  await expect(page.locator('.history .record')).toHaveCount(3)
  await page.reload()
  await expect(page.locator('.history .record')).toHaveCount(3)
  await page.getByRole('button', { name: 'Workout actions', exact: true }).first().click()
  await page.getByRole('button', { name: 'Perform again', exact: true }).first().click()
  await expect(active.getByRole('checkbox')).toHaveCount(9)
  await page.reload()
  await expect(active.getByRole('checkbox')).toHaveCount(9)
  for (const checkbox of await active.getByRole('checkbox').all()) await expect(checkbox).not.toBeChecked()
  await page.getByRole('link', { name: 'History', exact: true }).click()
  await page.getByRole('button', { name: 'Repeat this day' }).click()
  await expect(page.getByText('A workout is in progress. Replace it with this workout?')).toBeVisible()
  await page.getByRole('button', { name: 'Replace & start' }).click()
  await expect(active.getByRole('checkbox')).toHaveCount(9)
  await active.getByRole('button', { name: 'Discard workout', exact: true }).click()
  await active.locator('.planner-confirm').getByRole('button', { name: 'Discard workout' }).click()
  await expect(active).toHaveCount(0)
  await page.getByRole('link', { name: 'History', exact: true }).click()
  await expect(page.locator('.history .record')).toHaveCount(3)
})

test('units, template editing, language switching and mobile layout', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/#/templates')
  await page.getByRole('button', { name: 'Create template', exact: true }).click()
  await page.getByLabel('Template name').fill('Strength')
  const editor = page.locator('.template-editor')
  await editor.getByRole('button', { name: 'Add exercise' }).click()
  await expect(editor.getByRole('spinbutton', { name: /Weight|reps/ })).toHaveCount(0)
  await editor.getByRole('spinbutton', { name: 'sets', exact: true }).fill('4')
  await selectPreference(page, 'unit', 'lb')
  await editor.getByRole('button', { name: 'Save template' }).click()
  await page.locator('.template-card').getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByLabel('Template name').fill('Updated strength')
  await editor.getByRole('button', { name: 'Save template' }).click()
  await page.getByRole('button', { name: 'Start workout', exact: true }).click()
  const active = page.locator('#current-workout')
  await expect(active.getByRole('checkbox')).toHaveCount(4)
  await expect(active.getByRole('checkbox').first()).toBeDisabled()
  await expect(active.getByRole('spinbutton', { name: /^Weight / }).first()).toHaveValue('')
  await expect(active.getByRole('spinbutton', { name: /^reps / }).first()).toHaveValue('')
  const item = await page.evaluate(() => JSON.parse(localStorage.getItem('workingout.planner.v1')).templates[0].items[0])
  expect(item.weight).toBeUndefined()
  expect(item.reps).toBeUndefined()
  for (const language of ['ja', 'es', 'zh', 'en']) {
    await selectPreference(page, 'language', language)
    await expect(page.locator('html')).toHaveAttribute('lang', language)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
  await page.reload()
  await expect(page.getByLabel('Weight unit', { exact: true })).toHaveValue('lb')
  await page.getByRole('link', { name: 'Templates', exact: true }).click()
  await expect(page.locator('.template-card')).toContainText('Updated strength')
  await page.locator('.template-card').getByRole('button', { name: 'Delete', exact: true }).click()
  await page.locator('.template-card .planner-confirm').getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(page.locator('.template-card')).toHaveCount(0)
  await page.getByRole('link', { name: 'Workout', exact: true }).click()
  await expect(page.locator('#current-workout')).toBeVisible()
})
