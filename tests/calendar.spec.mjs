import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-15T12:00:00') })
  await page.addInitScript(() => {
    if (localStorage.getItem('workingout.records.v1')) return
    localStorage.setItem('workingout.records.v1', JSON.stringify(['2026-10-03', '2026-10-03', '2026-10-14', '2026-09-30', '2024-02-29'].map((date, index) => ({ id: `record-${index}`, date, exercise: `Exercise ${index}`, weight: 20, reps: 10, sets: 3, note: '' }))))
  })
})

test('recorded dates open filtered history with reload, back and clear support', async ({ page }) => {
  await page.goto('/')
  const calendar = page.locator('.workout-calendar')
  await expect(calendar.getByRole('heading', { name: 'October 2026' })).toBeVisible()
  await expect(calendar.locator('.has-workout')).toHaveCount(2)
  await expect(calendar.locator('.calendar-total')).toHaveText('2 days')
  await expect(calendar.locator('[aria-current="date"]')).toHaveText('15')
  await calendar.locator('[data-date="2026-10-03"]').click()
  await expect(page).toHaveURL(/#\/history\?date=2026-10-03$/)
  await expect(page.locator('#filter-date')).toHaveValue('2026-10-03')
  await expect(page.locator('.history .record')).toHaveCount(2)
  await page.reload()
  await expect(page.locator('.history .record')).toHaveCount(2)
  await expect(page.locator('#filter-date')).toHaveValue('2026-10-03')
  await page.getByRole('button', { name: 'Clear', exact: true }).click()
  await expect(page.locator('.history .record')).toHaveCount(5)
  await page.goBack()
  await expect(page.locator('.history .record')).toHaveCount(2)
  await page.locator('.history-calendar summary').click()
  await expect(page.locator('.calendar-day.is-selected')).toContainText('3')
  await page.locator('.history-calendar [data-date="2026-10-14"]').click()
  await expect(page.locator('.history .record')).toHaveCount(1)
  await page.locator('.history .record .actions').getByRole('button', { name: 'Delete', exact: false }).click()
  await page.locator('.delete-confirm').getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('link', { name: 'Home', exact: true }).click()
  await expect(calendar.locator('[data-date="2026-10-14"]')).toHaveCount(0)
  await expect(calendar.locator('.has-workout')).toHaveCount(1)
})

test('month changes, leap years and localized mobile calendar', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 812 })
  await page.goto('/#/calendar')
  const calendar = page.locator('.workout-calendar')
  await calendar.getByRole('button', { name: 'Previous month', exact: true }).click()
  await expect(calendar.locator('[data-date="2026-09-30"]')).toBeVisible()
  await calendar.getByRole('button', { name: 'Today', exact: true }).click()
  await expect(calendar.getByRole('heading', { name: 'October 2026' })).toBeVisible()
  await calendar.getByLabel('Choose month', { exact: true }).fill('2024-02')
  await expect(calendar.locator('[data-date="2024-02-29"]')).toBeVisible()
  await expect(calendar.locator('.calendar-grid > *').nth(32)).toContainText('29')
  await calendar.getByLabel('Choose month', { exact: true }).fill('2025-12')
  await calendar.getByRole('button', { name: 'Next month', exact: true }).click()
  await expect(calendar.getByRole('heading', { name: 'January 2026' })).toBeVisible()
  await expect(calendar.getByText('No workouts recorded this month yet.')).toBeVisible()
  for (const language of ['en', 'ja', 'es', 'zh']) {
    await page.locator('.settings select').first().selectOption(language)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await expect(calendar.locator('.calendar-weekdays > span')).toHaveCount(7)
  }
  await page.locator('.settings select').first().selectOption('en')
  await calendar.getByRole('button', { name: 'Today', exact: true }).click()
  await calendar.screenshot({ path: 'test-results/mobile-calendar.png', animations: 'disabled' })
})

test('calendar sits to the right on desktop and opens a separate page on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/')
  const main = await page.locator('.home-main').boundingBox()
  const calendar = await page.locator('.home-calendar-sidebar').boundingBox()
  expect(calendar.x).toBeGreaterThanOrEqual(main.x + main.width)
  expect(Math.abs(calendar.y - main.y)).toBeLessThan(2)
  await page.screenshot({ path: 'test-results/home-calendar-desktop.png', fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('.home-calendar-sidebar')).toBeHidden()
  await page.locator('.page-nav a[href="#/calendar"]').click()
  await expect(page.locator('.calendar-page .workout-calendar')).toBeVisible()
  await expect(page.locator('.home-main')).toHaveCount(0)
  await page.locator('.calendar-page [data-date="2026-10-03"]').click()
  await expect(page.locator('.history .record')).toHaveCount(2)
})
