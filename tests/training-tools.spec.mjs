import { selectPreference } from './helpers/preferences.mjs'
import { test, expect } from '@playwright/test'

async function seed(page) {
  await page.goto('/')
  await page.evaluate(() => {
    const base = { exercise: 'Press', weight: 50, reps: 8, sets: 1, note: '' }
    localStorage.setItem('workingout.records.v1', JSON.stringify([
      { ...base, id: 'old', date: '2026-10-12' },
      { ...base, id: 'new', date: '2026-10-14', weight: 60, reps: 10, setDetails: [{ weight: 60, reps: 10 }] },
      { ...base, id: 'warm', date: '2026-10-13', weight: 999, reps: 100, setDetails: [{ weight: 999, reps: 100, type: 'warmup' }] },
    ]))
    localStorage.setItem('workingout.planner.v1', JSON.stringify({ session: null, templates: [{ id: 'plan', name: 'Routine', restSeconds: 120, items: [{ id: 'press', exercise: 'Press', sets: 2 }, { id: 'row', exercise: 'Row', sets: 1 }] }] }))
  })
  await page.reload()
}

test('progress chart orders workouts, excludes warmups, converts units and marks PRs', async ({ page }) => {
  await seed(page)
  await page.setViewportSize({ width: 375, height: 812 })
  await page.getByRole('link', { name: 'Progress', exact: true }).click()
  await page.locator('.exercise-trends > summary').click()
  const progress = page.locator('.training-progress')
  await expect(progress.locator('.pr-stats')).toContainText('60 kg')
  await expect(progress.locator('tbody tr')).toHaveCount(2)
  await expect(progress.locator('tbody tr').first()).toContainText('2026-10-12')
  await expect(progress.locator('.progress-chart circle')).toHaveCount(2)
  await selectPreference(page, 'unit', 'lb')
  await expect(progress.locator('.pr-stats')).toContainText('132.28 lb')
  await progress.getByRole('combobox').nth(1).selectOption('reps')
  await expect(progress.getByRole('img')).toHaveAttribute('aria-label', /reps/)
  await page.getByRole('link', { name: 'History', exact: true }).click()
  await expect(page.locator('.record').filter({ hasText: '999' }).locator('.pr-badge')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('reordering, set types, PRs, timer adjustments and repeat retain workout details', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-15T12:00:00') })
  await seed(page)
  await page.getByRole('link', { name: 'Templates', exact: true }).click()
  await page.locator('.template-card').getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByRole('button', { name: 'Move up: Row', exact: true }).click()
  await page.getByRole('button', { name: 'Save template', exact: true }).click()
  await page.getByRole('button', { name: 'Start workout', exact: true }).click()
  const active = page.locator('#current-workout')
  await expect(active.locator('.live-exercise h3').first()).toHaveText('Row')
  await active.getByRole('button', { name: 'Move up: Press', exact: true }).click()
  await expect(active.locator('.live-exercise h3').first()).toHaveText('Press')
  const press = active.locator('.live-exercise').first()
  await press.getByRole('spinbutton', { name: 'Weight 1 (kg)', exact: true }).fill('100')
  await press.getByRole('button', { name: 'Set type 1', exact: true }).click()
  await expect(page.locator('.set-type-popup:popover-open')).toBeVisible()
  await page.locator('.set-type-popup:popover-open').getByRole('button', { name: 'Warm-up', exact: true }).click()
  await expect(page.locator('.set-type-popup:popover-open')).toHaveCount(0)
  await press.getByRole('checkbox').first().check()
  await expect(press.locator('.pr-badge')).toHaveCount(0)
  await expect(active.locator('output')).toHaveText('02:00')
  await active.getByRole('button', { name: '+30 seconds', exact: true }).click()
  await expect(active.locator('output')).toHaveText('02:30')
  await active.getByRole('button', { name: '-30 seconds', exact: true }).click()
  await expect(active.locator('output')).toHaveText('02:00')
  await active.getByRole('button', { name: 'Pause', exact: true }).click()
  await active.getByRole('button', { name: '+30 seconds', exact: true }).click()
  await page.clock.runFor(10000)
  await expect(active.locator('output')).toHaveText('02:30')
  await press.getByRole('spinbutton', { name: 'Weight 2 (kg)', exact: true }).fill('70')
  await press.getByRole('spinbutton', { name: 'reps 2', exact: true }).fill('8')
  await press.getByRole('button', { name: 'Set type 2', exact: true }).click()
  await page.locator('.set-type-popup:popover-open').getByRole('button', { name: 'Drop set', exact: true }).click()
  await press.getByRole('checkbox').nth(1).check()
  await expect(press.locator('.pr-badge')).toHaveText('New PR!')
  await page.reload()
  await expect(active.locator('.live-exercise h3').first()).toHaveText('Press')
  await expect(press.locator('.set-number-control').nth(0)).toHaveAttribute('data-set-type', 'warmup')
  await active.getByRole('button', { name: 'Finish & save to history', exact: true }).click()
  await active.getByRole('button', { name: 'Remove unfinished sets & save', exact: true }).click()
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('workingout.records.v1')).at(-1))
  expect(saved.setDetails.map(set => set.type)).toEqual(['warmup', 'drop'])
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click()
  await page.locator('.workout-history-card').first().getByRole('button', { name: 'Workout actions', exact: true }).click()
  await page.getByRole('button', { name: 'Perform again', exact: true }).click()
  await expect(press.locator('.set-number-control').nth(1)).toHaveAttribute('data-set-type', 'drop')
  await press.getByRole('button', { name: 'Set type 2', exact: true }).click()
  await expect(page.locator('.set-type-popup:popover-open').getByRole('button', { name: 'Drop set', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('Escape')
  await expect(page.locator('.set-type-popup:popover-open')).toHaveCount(0)
  await page.getByRole('link', { name: 'Templates', exact: true }).click()
  const template = await page.evaluate(() => JSON.parse(localStorage.getItem('workingout.planner.v1')).templates[0])
  expect(template.items.map(item => item.exercise)).toEqual(['Row', 'Press'])
})
