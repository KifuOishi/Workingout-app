import { test, expect } from '@playwright/test'

test('per-set values, previous results, completion, rest and exact history survive repeat', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-15T12:00:00') })
  await page.goto('/#/templates')
  await page.getByRole('link', { name: 'History', exact: true }).click()
  await page.getByRole('button', { name: 'Add a past record' }).click()
  await page.locator('#record-form').getByRole('spinbutton', { name: 'Weight (kg)' }).fill('100')
  await page.locator('#record-form').getByRole('button', { name: 'Add record' }).click()
  await page.getByRole('link', { name: 'Templates', exact: true }).click()
  await page.getByRole('button', { name: 'Create template', exact: true }).click()
  await page.getByLabel('Template name').fill('Set tracking')
  const editor = page.locator('.template-editor')
  await editor.getByRole('button', { name: 'Add exercise' }).click()
  await editor.getByRole('button', { name: 'Save template' }).click()
  await page.getByRole('button', { name: 'Start workout', exact: true }).click()
  const active = page.locator('#current-workout')
  await expect(active.locator('.previous-set').first()).toHaveText('100 kg × 10')
  await active.getByRole('button', { name: 'Add set', exact: false }).click()
  await expect(active.getByRole('checkbox')).toHaveCount(4)
  await active.getByRole('button', { name: 'Remove set 4', exact: true }).click()
  await expect(active.getByRole('checkbox')).toHaveCount(3)
  const weights = [60, 65, 70]
  const reps = [10, 8, 6]
  for (let i = 0; i < 3; i++) {
    await active.getByRole('spinbutton', { name: `Weight ${i + 1} (kg)`, exact: true }).fill(String(weights[i]))
    await active.getByRole('spinbutton', { name: `reps ${i + 1}`, exact: true }).fill(String(reps[i]))
  }
  await active.getByRole('spinbutton', { name: 'Rest interval 1', exact: true }).fill('2')
  await active.getByRole('checkbox').first().check()
  await expect(active.getByRole('button', { name: 'Finish & save to history' })).toBeEnabled()
  await page.clock.runFor(2500)
  await expect(active.getByRole('alert')).toContainText('Rest is over')
  await page.reload()
  await expect(active.getByRole('checkbox').first()).toBeChecked()
  await expect(active.getByRole('spinbutton', { name: 'Weight 2 (kg)', exact: true })).toHaveValue('65')
  for (const checkbox of await active.getByRole('checkbox').all()) await checkbox.check()
  await active.getByRole('button', { name: 'Finish & save to history' }).click()
  const records = await page.evaluate(() => JSON.parse(localStorage.getItem('workingout.records.v1')))
  expect(records[1].setDetails).toEqual([{ weight: 60, reps: 10 }, { weight: 65, reps: 8 }, { weight: 70, reps: 6 }])
  expect(records[1].sets).toBe(3)
  await page.reload()
  await page.getByRole('link', { name: 'Home', exact: true }).click()
  await expect(page.locator('.stats > div').nth(2)).toContainText('4,540')
  await page.getByRole('link', { name: 'History', exact: true }).click()
  for (const summary of await page.locator('.workout-history-card > details > summary').all()) await summary.click()
  await page.locator('.history .record').first().getByRole('button', { name: 'Repeat exercise', exact: true }).click()
  await expect(active.locator('.previous-set').nth(1)).toHaveText('65 kg × 8')
  await expect(active.getByRole('spinbutton', { name: 'Weight 2 (kg)', exact: true })).toHaveValue('65')
  await expect(active.getByRole('checkbox').first()).not.toBeChecked()
  await page.getByLabel('Weight unit', { exact: true }).selectOption('lb')
  await expect(active.getByRole('spinbutton', { name: 'Weight 1 (lb)', exact: true })).toHaveValue('132.277357')
  await page.getByLabel('Weight unit', { exact: true }).selectOption('kg')
  await expect(active.getByRole('spinbutton', { name: 'Weight 1 (kg)', exact: true })).toHaveValue('60')
  await page.setViewportSize({ width: 375, height: 812 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await active.screenshot({ path: 'test-results/set-workout.png' })
})

test('existing exercise-level progress migrates to set-level progress', async ({ page }) => {
  await page.goto('/#/templates')
  await page.getByRole('button', { name: 'Create template', exact: true }).click()
  await page.getByLabel('Template name').fill('Migration')
  const editor = page.locator('.template-editor')
  await editor.getByRole('button', { name: 'Add exercise' }).click()
  await editor.getByRole('button', { name: 'Save template' }).click()
  await page.getByRole('button', { name: 'Start workout', exact: true }).click()
  await page.evaluate(() => {
    const state = JSON.parse(localStorage.getItem('workingout.planner.v1'))
    delete state.session.setRows
    delete state.session.startedAt
    state.session.completed = [state.session.items[0].id]
    localStorage.setItem('workingout.planner.v1', JSON.stringify(state))
  })
  await page.reload()
  for (const checkbox of await page.locator('#current-workout').getByRole('checkbox').all()) await expect(checkbox).toBeChecked()
  await expect(page.locator('#current-workout').getByRole('button', { name: 'Finish & save to history' })).toBeEnabled()
})
