import { test, expect } from '@playwright/test'

test('previous values are subdued, editable, checkable and usable when completing unfinished sets', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => {
    localStorage.setItem('workingout.records.v1', JSON.stringify([{ id: 'old', date: '2026-10-14', exercise: 'Press', weight: 50, reps: 8, sets: 2, note: '', setDetails: [{ weight: 50, reps: 8 }, { weight: 45, reps: 10 }] }]))
    localStorage.setItem('workingout.planner.v1', JSON.stringify({ session: null, templates: [{ id: 'plan', name: 'Routine', restSeconds: 0, items: [{ id: 'exercise', exercise: 'Press', sets: 2 }] }] }))
  })
  await page.goto('/#/templates')
  await page.reload()
  await page.getByRole('button', { name: 'Start workout', exact: true }).click()
  const active = page.locator('#current-workout')
  const weight = active.getByRole('spinbutton', { name: 'Weight 1 (kg)', exact: true })
  const reps = active.getByRole('spinbutton', { name: 'reps 1', exact: true })
  await expect(weight).toHaveValue('50')
  await expect(reps).toHaveValue('8')
  await expect(weight).toHaveClass('suggested-value')
  await page.getByLabel('Weight unit', { exact: true }).selectOption('lb')
  await expect(weight).toHaveCount(0)
  await expect(active.getByRole('spinbutton', { name: 'Weight 1 (lb)', exact: true })).toHaveValue('110.231131')
  await page.getByLabel('Weight unit', { exact: true }).selectOption('kg')
  await weight.fill('55')
  await expect(weight).not.toHaveClass('suggested-value')
  await expect(reps).toHaveClass('suggested-value')
  await active.getByRole('checkbox').first().check()
  await expect(reps).not.toHaveClass('suggested-value')
  await page.reload()
  await expect(active.getByRole('checkbox').first()).toBeChecked()
  await expect(active.getByRole('spinbutton', { name: 'Weight 2 (kg)', exact: true })).toHaveClass('suggested-value')
  await active.getByRole('button', { name: 'Finish & save to history', exact: true }).click()
  await active.getByRole('button', { name: 'Mark remaining sets complete & save', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Workout complete', exact: true })).toBeVisible()
  const records = await page.evaluate(() => JSON.parse(localStorage.getItem('workingout.records.v1')))
  expect(records.at(-1).setDetails).toEqual([{ weight: 55, reps: 8 }, { weight: 45, reps: 10 }])
})
