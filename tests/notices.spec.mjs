import { test, expect } from '@playwright/test'

test('success notices expire, restart for repeated actions, and clear when navigating away', async ({ page }) => {
  await page.clock.install()
  await page.goto('/#/history')
  await page.getByRole('button', { name: 'Add a past record', exact: true }).click()
  const add = page.locator('#record-form').getByRole('button', { name: 'Add record' })
  const recorded = page.locator('.notice').filter({ hasText: 'Workout recorded.' })
  await add.click()
  await expect(recorded).toBeVisible()
  await page.clock.runFor(3000)
  await add.click()
  await page.clock.runFor(1500)
  await expect(recorded).toBeVisible()
  await page.clock.runFor(2500)
  await expect(recorded).toHaveCount(0)
  await add.click()
  await page.getByRole('link', { name: 'Templates', exact: true }).click()
  await expect(recorded).toHaveCount(0)
  await page.getByRole('link', { name: 'History', exact: true }).click()
  await expect(recorded).toHaveCount(0)

  await page.getByRole('link', { name: 'Templates', exact: true }).click()
  await page.getByRole('button', { name: 'Create template', exact: true }).click()
  const editor = page.locator('.template-editor')
  await editor.getByLabel('Template name').fill('Notice test')
  await editor.getByRole('button', { name: 'Add exercise' }).click()
  await editor.getByRole('button', { name: 'Save template', exact: true }).click()
  const saved = page.locator('.notice').filter({ hasText: 'Template saved.' })
  await expect(saved).toBeVisible()
  await page.clock.runFor(4000)
  await expect(saved).toHaveCount(0)
  await page.locator('.template-card').getByRole('button', { name: 'Edit', exact: true }).click()
  await editor.getByRole('button', { name: 'Save template', exact: true }).click()
  await expect(saved).toBeVisible()
  await page.getByRole('link', { name: 'History', exact: true }).click()
  await page.getByRole('link', { name: 'Templates', exact: true }).click()
  await expect(saved).toHaveCount(0)
})

test('finishing a workout does not leave a stale planner notice on templates', async ({ page }) => {
  await page.clock.install()
  await page.goto('/#/workout')
  await page.getByRole('button', { name: 'Start empty workout', exact: true }).click()
  await page.locator('.session-exercise-actions button').click()
  await page.locator('.session-add-form button[type="submit"]').click()
  await page.locator('#current-workout').getByRole('checkbox').check()
  await page.locator('#current-workout').getByRole('button', { name: 'Finish & save to history', exact: true }).click()
  await page.locator('.finish-choice').getByRole('button', { name: 'Finish & save to history', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('link', { name: 'Templates', exact: true }).click()
  await expect(page.locator('.notice')).toHaveCount(0)
})
