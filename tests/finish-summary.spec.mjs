import { selectPreference } from './helpers/preferences.mjs'
import { test, expect } from '@playwright/test'

async function begin(page) {
  await page.clock.install({ time: new Date('2026-10-15T12:00:00') })
  await page.goto('/#/templates')
  await page.evaluate(() => {
    const item = { weight: 60, reps: 10, sets: 3, note: '', category: '胸' }
    localStorage.setItem('workingout.planner.v1', JSON.stringify({ session: null, templates: [{ id: 'routine', name: 'Training day', restSeconds: 0, items: [{ ...item, id: 'one', exercise: 'First exercise' }, { ...item, id: 'two', exercise: 'Second exercise' }] }] }))
  })
  await page.reload()
  await page.clock.pauseAt(new Date('2026-10-15T12:01:00'))
  await page.getByRole('button', { name: 'Start workout', exact: true }).click()
  for (const input of await page.locator('#current-workout').getByRole('spinbutton', { name: /^Weight / }).all()) await input.fill('60')
  for (const input of await page.locator('#current-workout').getByRole('spinbutton', { name: /^reps / }).all()) await input.fill('10')
  return page.locator('#current-workout')
}

test('remove unfinished sets, display summary and elapsed time, preserve the template', async ({ page }) => {
  const active = await begin(page)
  await active.getByRole('spinbutton', { name: 'Weight 1 (kg)', exact: true }).first().fill('65')
  await active.getByRole('checkbox').first().check()
  await page.clock.runFor(125000)
  await active.getByRole('button', { name: 'Finish & save to history' }).click()
  await expect(active.locator('.finish-choice')).toBeVisible()
  await active.getByRole('button', { name: 'Remove unfinished sets & save', exact: true }).click()
  const summary = page.getByRole('dialog', { name: 'Workout complete', exact: true })
  await expect(summary).toBeVisible()
  expect(await summary.evaluate(element => element.matches(':modal'))).toBe(true)
  await expect(summary.getByRole('button', { name: 'Close', exact: true })).toBeFocused()
  await expect(summary.locator('.summary-duration')).toHaveText('00:02:05')
  await expect(summary.getByRole('heading', { name: 'First exercise' })).toBeVisible()
  await expect(summary.getByRole('heading', { name: 'Second exercise' })).toHaveCount(0)
  const saved = await page.evaluate(() => ({ records: JSON.parse(localStorage.getItem('workingout.records.v1')), planner: JSON.parse(localStorage.getItem('workingout.planner.v1')) }))
  expect(saved.records).toHaveLength(1)
  expect(saved.records[0].setDetails).toEqual([{ weight: 65, reps: 10 }])
  expect(saved.records[0].durationSeconds).toBe(125)
  expect(saved.planner.templates[0].items.map(item => item.sets)).toEqual([3, 3])
  expect(saved.planner.session).toBeNull()
  await page.reload()
  await page.getByRole('button', { name: 'Workout actions', exact: true }).first().click()
  await page.getByRole('button', { name: 'View summary', exact: true }).click()
  await expect(summary.locator('.summary-duration')).toHaveText('00:02:05')
  await page.keyboard.press('Escape')
  await expect(summary).toHaveCount(0)
  await selectPreference(page, 'unit', 'lb')
  await page.getByRole('button', { name: 'Workout actions', exact: true }).first().click()
  await page.getByRole('button', { name: 'View summary', exact: true }).click()
  await expect(summary.locator('.summary-exercises')).toContainText('143.3 lb')
  await page.setViewportSize({ width: 375, height: 812 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const bounds = await summary.boundingBox()
  expect(bounds.x).toBeGreaterThanOrEqual(0)
  expect(bounds.y).toBeGreaterThanOrEqual(0)
  expect(bounds.y + bounds.height).toBeLessThanOrEqual(812)
  await summary.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(summary).toHaveCount(0)
  expect(await page.evaluate(() => document.body.style.overflow)).not.toBe('hidden')
})

test('mark unperformed sets complete saves all entered sets without changing template', async ({ page }) => {
  const active = await begin(page)
  await active.getByRole('checkbox').first().check()
  await active.getByRole('button', { name: 'Finish & save to history' }).click()
  await active.locator('.finish-choice').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(active.getByRole('checkbox').first()).toBeChecked()
  await active.getByRole('button', { name: 'Finish & save to history' }).click()
  await active.getByRole('button', { name: 'Mark remaining sets complete & save', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Workout complete', exact: true })).toBeVisible()
  const records = await page.evaluate(() => JSON.parse(localStorage.getItem('workingout.records.v1')))
  expect(records.map(record => record.sets)).toEqual([3, 3])
  expect(records[0].workoutId).toBe(records[1].workoutId)
  expect(records[0].durationSeconds).toBe(records[1].durationSeconds)
})

test('all completed sets require confirmation and an empty completion cannot be saved', async ({ page }) => {
  const active = await begin(page)
  await active.getByRole('button', { name: 'Finish & save to history' }).click()
  await active.getByRole('button', { name: 'Remove unfinished sets & save', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('No completed sets to save')
  await active.locator('.finish-choice').getByRole('button', { name: 'Cancel', exact: true }).click()
  for (const checkbox of await active.getByRole('checkbox').all()) await checkbox.check()
  await active.getByRole('button', { name: 'Finish & save to history' }).click()
  const confirmation = active.locator('.finish-choice')
  await expect(confirmation).toContainText('Are you sure you want to finish this workout?')
  await expect(page.getByRole('dialog', { name: 'Workout complete', exact: true })).toHaveCount(0)
  await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(active.getByRole('checkbox').first()).toBeChecked()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('workingout.planner.v1')).session)).not.toBeNull()
  await active.getByRole('button', { name: 'Finish & save to history' }).click()
  await confirmation.getByRole('button', { name: 'Finish & save to history', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Workout complete', exact: true })).toBeVisible()
  await expect(page.locator('.finish-choice')).toHaveCount(0)
})
