import { test, expect } from '@playwright/test'

test('optional reflections save per workout, survive reload, can be cleared and are not copied on repeat', async ({ page }) => {
  await page.goto('/#/templates')
  await page.evaluate(() => localStorage.setItem('workingout.planner.v1', JSON.stringify({ session: null, templates: [{ id: 'plan', name: 'Routine', restSeconds: 0, items: [{ id: 'one', exercise: 'Press', sets: 1 }, { id: 'two', exercise: 'Row', sets: 1 }] }] })))
  await page.reload()
  await page.getByRole('button', { name: 'Start workout', exact: true }).click()
  const active = page.locator('#current-workout')
  for (const input of await active.getByRole('spinbutton', { name: /^Weight / }).all()) await input.fill('40')
  for (const input of await active.getByRole('spinbutton', { name: /^reps / }).all()) await input.fill('8')
  for (const checkbox of await active.getByRole('checkbox').all()) await checkbox.check()
  await active.getByRole('button', { name: 'Finish & save to history', exact: true }).click()
  const reflection = page.getByRole('region', { name: 'How did it feel?', exact: true })
  await expect(reflection).toBeVisible()
  const records = () => page.evaluate(() => JSON.parse(localStorage.getItem('workingout.records.v1')))
  expect((await records()).every(record => !record.feeling && !record.workoutNote)).toBe(true)
  await reflection.getByLabel('Effort', { exact: true }).selectOption('hard')
  await reflection.getByLabel('Workout note', { exact: true }).fill('Low energy today.\nTry earlier next time.')
  expect((await records()).map(record => record.feeling)).toEqual(['hard', 'hard'])
  expect((await records()).every(record => record.workoutNote === 'Low energy today.\nTry earlier next time.')).toBe(true)
  await page.reload()
  const card = page.locator('.workout-history-card').first()
  await card.locator('summary').click()
  await expect(card.locator('.history-reflection')).toContainText('Tough')
  await expect(card.locator('.history-reflection')).toContainText('Low energy today.')
  await card.getByRole('button', { name: 'Workout actions', exact: true }).click()
  await page.getByRole('button', { name: 'View summary', exact: true }).click()
  await expect(reflection.getByLabel('Effort', { exact: true })).toHaveValue('hard')
  await reflection.getByLabel('Effort', { exact: true }).selectOption('')
  await reflection.getByLabel('Workout note', { exact: true }).fill('')
  expect((await records()).every(record => !record.feeling && !record.workoutNote)).toBe(true)
  await reflection.getByLabel('Effort', { exact: true }).selectOption('easy')
  await reflection.getByLabel('Workout note', { exact: true }).fill('Original workout only')
  await card.getByRole('button', { name: 'Workout actions', exact: true }).click()
  await page.getByRole('button', { name: 'Perform again', exact: true }).click()
  for (const checkbox of await active.getByRole('checkbox').all()) await checkbox.check()
  await active.getByRole('button', { name: 'Finish & save to history', exact: true }).click()
  await expect(reflection.getByLabel('Effort', { exact: true })).toHaveValue('')
  await expect(reflection.getByLabel('Workout note', { exact: true })).toHaveValue('')
  expect((await records()).slice(2).every(record => !record.feeling && !record.workoutNote)).toBe(true)
})
