import { test, expect } from '@playwright/test'
test.use({ hasTouch: true })

async function start(page, count = 3) {
  await page.goto('/#/templates')
  await page.evaluate(count => {
    const items = ['First', 'Second', 'Third'].slice(0, count).map((exercise, index) => ({ id: String(index), exercise, sets: 1 }))
    localStorage.setItem('workingout.planner.v1', JSON.stringify({ session: null, templates: [{ id: 'plan', name: 'Drag routine', restSeconds: 0, items }] }))
  }, count)
  await page.reload()
  await page.getByRole('button', { name: 'Start workout', exact: true }).click()
  const active = page.locator('#current-workout')
  for (const input of await active.getByRole('spinbutton', { name: /^Weight / }).all()) await input.fill('25')
  for (const input of await active.getByRole('spinbutton', { name: /^reps / }).all()) await input.fill('8')
  await active.getByRole('checkbox').first().check()
  return active
}

test('mouse dragging reorders exercises without losing set values or completion and escape cancels', async ({ page }) => {
  await page.setViewportSize({ width: 1100, height: 2200 })
  const active = await start(page)
  const handle = active.getByRole('button', { name: 'Drag to reorder: First', exact: true })
  const source = await handle.boundingBox()
  await page.mouse.move(source.x + source.width / 2, source.y + source.height / 2)
  await page.mouse.down()
  await expect(active.locator('.set-entry').first()).toBeHidden()
  expect((await active.locator('.live-exercise').first().boundingBox()).height).toBeLessThan(120)
  const target = await active.getByRole('button', { name: 'Drag to reorder: Third', exact: true }).boundingBox()
  await page.mouse.move(target.x + target.width / 2, target.y + target.height / 2, { steps: 20 })
  await expect(active.locator('.live-exercise').nth(2)).toHaveClass(/drag-target/)
  await page.mouse.up()
  await expect(active.locator('.set-entry').first()).toBeVisible()
  await expect(active.locator('.live-exercise h3')).toHaveText(['Second', 'Third', 'First'])
  await page.reload()
  await expect(active.locator('.live-exercise h3')).toHaveText(['Second', 'Third', 'First'])
  await expect(active.locator('.live-exercise').last().getByRole('checkbox')).toBeChecked()
  await expect(active.locator('.live-exercise').last().getByRole('spinbutton', { name: /^Weight / })).toHaveValue('25')
  const next = await active.getByRole('button', { name: 'Drag to reorder: Second', exact: true }).boundingBox()
  await page.mouse.move(next.x + 10, next.y + 10)
  await page.mouse.down()
  await page.keyboard.press('Escape')
  await page.mouse.up()
  await expect(page.locator('.exercise-drag-preview')).toHaveCount(0)
  await expect(active.locator('.live-exercise h3')).toHaveText(['Second', 'Third', 'First'])
})

test('touch dragging works on mobile and leaves the saved template unchanged', async ({ page, context }) => {
  await page.setViewportSize({ width: 375, height: 1800 })
  const active = await start(page, 2)
  const source = await active.getByRole('button', { name: 'Drag to reorder: First', exact: true }).boundingBox()
  const cdp = await context.newCDPSession(page)
  const point = (rect) => ({ x: rect.x + rect.width / 2, y: rect.y + rect.height / 2 })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [point(source)] })
  await expect(active.locator('.set-entry').first()).toBeHidden()
  const target = await active.getByRole('button', { name: 'Drag to reorder: Second', exact: true }).boundingBox()
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [point(target)] })
  await expect(active.locator('.live-exercise').nth(1)).toHaveClass(/drag-target/)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect(active.locator('.set-entry').first()).toBeVisible()
  await expect(active.locator('.live-exercise h3')).toHaveText(['Second', 'First'])
  const template = await page.evaluate(() => JSON.parse(localStorage.getItem('workingout.planner.v1')).templates[0])
  expect(template.items.map(item => item.exercise)).toEqual(['First', 'Second'])
})

test('dragging near the screen edge scrolls a long workout and cancelling keeps the order', async ({ page, context }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  const active = await start(page)
  const handle = active.getByRole('button', { name: 'Drag to reorder: First', exact: true })
  await handle.scrollIntoViewIfNeeded()
  const source = await handle.boundingBox()
  const before = await page.evaluate(() => scrollY)
  const cdp = await context.newCDPSession(page)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: source.x + 20, y: source.y + 20 }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: source.x + 20, y: 790 }] })
  await expect.poll(() => page.evaluate(() => scrollY)).toBeGreaterThan(before + 40)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] })
  await expect(page.locator('.exercise-drag-preview')).toHaveCount(0)
  await expect(active.locator('.set-entry').first()).toBeVisible()
  await expect(active.locator('.live-exercise h3')).toHaveText(['First', 'Second', 'Third'])
})
