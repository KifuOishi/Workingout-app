import { selectPreference } from './helpers/preferences.mjs'
import { test, expect } from '@playwright/test'

test('custom exercise creation saves its body part and equipment', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/#/workout')
  await page.getByRole('button', { name: 'Start empty workout', exact: true }).click()
  await page.locator('.session-exercise-actions button').click()
  const add = page.locator('.session-add-form')
  await add.getByRole('button', { name: 'Add an exercise to', exact: false }).click()
  const custom = add.locator('.custom-exercise')
  await custom.getByPlaceholder('e.g. My custom exercise').fill('My shoulder move')
  await custom.getByRole('button', { name: 'Shoulders', exact: true }).click()
  await custom.getByLabel('Equipment / type', { exact: true }).selectOption('dumbbell')
  await custom.getByRole('button', { name: 'Save and select exercise', exact: true }).click()
  await expect(add.getByRole('combobox')).toHaveValue('My shoulder move')
  await expect(add.getByRole('combobox')).toContainText('My shoulder move')
  await expect(add.locator('optgroup[label="Dumbbell"] option[value="My shoulder move"]')).toHaveCount(1)
  const exercises = await page.evaluate(() => JSON.parse(localStorage.getItem('workingout.exercises.v1')))
  expect(exercises[0]).toEqual({ category: '肩', name: 'My shoulder move', equipment: 'dumbbell' })
  await page.reload()
  await page.locator('.session-exercise-actions button').click()
  await page.locator('.session-add-form').getByRole('button', { name: 'Shoulders', exact: true }).click()
  await expect(page.locator('.session-add-form').getByRole('combobox')).toContainText('My shoulder move')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('only assisted chin-ups and dips show negative assistance, including history, repeat, units and progress', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-15T12:00:00') })
  await page.goto('/')
  await page.evaluate(() => {
    localStorage.setItem('workingout.records.v1', JSON.stringify([{ id: 'old', exercise: 'アシストチンニング', category: '背中', date: '2026-10-14', weight: 40, reps: 10, sets: 1, note: '' }]))
  })
  await page.reload()
  await page.getByRole('button', { name: 'Start empty workout', exact: true }).click()
  const active = page.locator('#current-workout')
  async function addExercise(bodyPart, label) {
    await page.locator('.session-exercise-actions button').click()
    const form = page.locator('.session-add-form')
    await form.getByRole('button', { name: bodyPart, exact: true }).click()
    await form.getByRole('combobox').selectOption({ label })
    await form.getByRole('button', { name: 'Add to workout', exact: true }).click()
  }
  await addExercise('Back', 'Assisted chin-up')
  const chin = active.locator('.live-exercise').first()
  const weight = chin.getByRole('spinbutton', { name: 'Weight 1 (kg)', exact: true })
  await expect(weight).toHaveValue('-40')
  await weight.fill('-50')
  await chin.getByRole('checkbox').check()
  await expect(chin.locator('.pr-badge')).toHaveCount(0)
  await chin.getByRole('checkbox').uncheck()
  await weight.fill('-30')
  await chin.getByRole('checkbox').check()
  await expect(chin.locator('.pr-badge')).toHaveText('New PR!')
  await addExercise('Chest', 'Assisted dip')
  const dip = active.locator('.live-exercise').nth(1)
  await dip.getByRole('spinbutton', { name: 'Weight 1 (kg)', exact: true }).fill('-15')
  await dip.getByRole('checkbox').check()
  await addExercise('Chest', 'Bench press')
  await expect(active.locator('.live-exercise').nth(2).getByRole('spinbutton', { name: 'Weight 1 (kg)', exact: true })).toHaveValue('20')
  await active.locator('.live-exercise').nth(2).getByRole('checkbox').check()
  await active.getByRole('button', { name: 'Finish & save to history', exact: true }).click()
  await page.locator('.finish-choice').getByRole('button', { name: 'Finish & save to history', exact: true }).click()
  await expect(page.locator('.summary-exercises')).toContainText('-30 kg')
  await expect(page.locator('.summary-exercises')).toContainText('-15 kg')
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click()
  await selectPreference(page, 'unit', 'lb')
  await page.getByRole('button', { name: 'Workout actions', exact: true }).first().click()
  await page.getByRole('button', { name: 'View summary', exact: true }).click()
  await expect(page.locator('.summary-exercises')).toContainText('-66.14 lb')
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('link', { name: 'Progress', exact: true }).click()
  await page.locator('.exercise-trends > summary').click()
  await expect(page).toHaveURL(/#\/progress$/)
  await expect(page.locator('.training-progress .pr-stats')).toContainText('-66.14 lb')
  await expect(page.locator('.training-progress tbody tr')).toHaveCount(2)
  await page.reload()
  await expect(page.locator('.training-progress')).toBeVisible()
  await page.getByRole('link', { name: 'History', exact: true }).click()
  await expect(page.locator('.training-progress')).toHaveCount(0)
  await page.locator('.workout-history-card').first().getByRole('button', { name: 'Workout actions', exact: true }).click()
  await page.getByRole('button', { name: 'Perform again', exact: true }).click()
  await expect(active.locator('.live-exercise').first().getByRole('spinbutton', { name: 'Weight 1 (lb)', exact: true })).toHaveValue('-66.14')
})

test('new exercise defaults use 40 lb and tapping selects the weight for replacement', async ({ page }) => {
  await page.goto('/')
  await selectPreference(page, 'unit', 'lb')
  await page.getByRole('link', { name: 'Workout', exact: true }).click()
  await page.getByRole('button', { name: 'Start empty workout', exact: true }).click()
  for (const [category, exercise, expected] of [['Back', 'Assisted chin-up', '-40'], ['Chest', 'Bench press', '40']]) {
    await page.locator('.session-exercise-actions button').click()
    const form = page.locator('.session-add-form')
    await form.getByRole('button', { name: category, exact: true }).click()
    await form.getByRole('combobox').selectOption({ label: exercise })
    await form.getByRole('button', { name: 'Add to workout', exact: true }).click()
    await expect(page.locator('.live-exercise').last().getByRole('spinbutton', { name: 'Weight 1 (lb)', exact: true })).toHaveValue(expected)
  }
  const weights = await page.evaluate(() => Object.values(JSON.parse(localStorage.getItem('workingout.planner.v1')).session.setRows).map(rows => rows[0].weight))
  expect(weights).toEqual([40 * 0.45359237, 40 * 0.45359237])
  await page.reload()
  const weight = page.locator('.live-exercise').first().getByRole('spinbutton', { name: 'Weight 1 (lb)', exact: true })
  await expect(weight).toHaveValue('-40')
  await weight.click()
  await weight.pressSequentially('25')
  await expect(weight).toHaveValue('-25')
  await selectPreference(page, 'unit', 'kg')
  await page.locator('.session-exercise-actions button').click()
  const form = page.locator('.session-add-form')
  await form.getByRole('button', { name: 'Chest', exact: true }).click()
  await form.getByRole('combobox').selectOption({ label: 'Bench press' })
  await form.getByRole('button', { name: 'Add to workout', exact: true }).click()
  await expect(page.locator('.live-exercise').last().getByRole('spinbutton', { name: 'Weight 1 (kg)', exact: true })).toHaveValue('20')
})
